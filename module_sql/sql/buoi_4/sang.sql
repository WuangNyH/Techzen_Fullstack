-- Câu 1
-- Lấy đơn hàng mới nhất cho từng khách hàng (chỉ lấy 10 khách hàng đầu)
SELECT
	C.CUSTOMER_ID,
	C.CUSTOMER_NAME,
	(
		SELECT ORDER_NUMBER
		FROM ORDERS O
		WHERE C.CUSTOMER_ID = O.CUSTOMER_ID
		ORDER BY ORDER_DATE DESC
		LIMIT 1
	) LASTEST_ORDER
FROM CUSTOMER C
LIMIT 10;

-- Câu 2.1
-- Lấy tất cả đơn hàng của những khách hàng VIP (GOLD hoặc PLATINUM).
SELECT
	O.CUSTOMER_ID,
	O.ORDER_NUMBER
FROM ORDERS O
WHERE O.CUSTOMER_ID IN (
	SELECT
		C.CUSTOMER_ID
	FROM CUSTOMER C
	WHERE C.VIP_TIER IN ('GOLD', 'PLATINUM')
);

-- Câu 2.2
-- Tìm khách hàng có ít nhất một đơn hàng bị hủy.
SELECT
	C.CUSTOMER_ID,
	C.CUSTOMER_NAME
FROM CUSTOMER C
WHERE EXISTS (
	SELECT 1
	FROM ORDERS O
	WHERE C.CUSTOMER_ID = O.CUSTOMER_ID AND STATUS = 'CANCELLED'
);

-- Câu 2.3
-- Tìm 10 khách hàng đầu tiên có tổng chi tiêu > 30000
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME
FROM CUSTOMER C
WHERE (
    SELECT SUM(O.TOTAL_AMOUNT)
    FROM ORDERS O
    WHERE O.CUSTOMER_ID = C.CUSTOMER_ID
) > 30000
LIMIT 10;

