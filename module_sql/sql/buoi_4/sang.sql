-- Tìm khách hàng có ít nhất một đơn CANCELLED và có ít nhất một đơn DELIVERED
SELECT
	C.CUSTOMER_ID,
	C.CUSTOMER_NAME
FROM CUSTOMER C
WHERE EXISTS (
	SELECT 1
	FROM ORDERS O
	WHERE C.CUSTOMER_ID = O.CUSTOMER_ID AND STATUS = 'CANCELLED'
) AND EXISTS (
	SELECT 1
	FROM ORDERS O
	WHERE C.CUSTOMER_ID = O.CUSTOMER_ID AND STATUS = 'DELIVERED'
);

-- Câu 2
-- Tìm ngày có tổng doanh thu cao nhất trong toàn bộ bảng orders
SELECT *
FROM (
	SELECT
		DATE_TRUNC('DAY', ORDER_DATE) AS DATE,
		SUM(TOTAL_AMOUNT) AS TONG_DOANH_THU
	FROM ORDERS
	GROUP BY DATE_TRUNC('DAY', ORDER_DATE)
	ORDER BY TONG_DOANH_THU DESC
)
LIMIT 1;

-- Bài nâng cao buổi 3
EXPLAIN ANALYZE
SELECT
	DATE_TRUNC('DAY', ORDER_DATE) AS DATE,
	SUM(TOTAL_AMOUNT) AS TONG_DOANH_THU
FROM ORDERS
GROUP BY DATE_TRUNC('DAY', ORDER_DATE)
ORDER BY DATE DESC
LIMIT 30;

CREATE MATERIALIZED VIEW MV_DAILY_SALES AS
SELECT
	DATE_TRUNC('DAY', ORDER_DATE) AS DATE,
	SUM(TOTAL_AMOUNT) AS TONG_DOANH_THU
FROM ORDERS
GROUP BY DATE_TRUNC('DAY', ORDER_DATE)
ORDER BY DATE DESC
WITH NO DATA;

REFRESH MATERIALIZED VIEW MV_DAILY_SALES;

EXPLAIN ANALYZE
SELECT *
FROM MV_DAILY_SALES
LIMIT 30;

