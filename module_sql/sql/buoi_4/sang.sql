);

-- Câu 2
-- Tìm tất cả khách hàng mà không tồn tại bất kỳ một đơn hàng có status DELIVERED
SELECT
	C.CUSTOMER_ID,
	C.CUSTOMER_NAME
FROM CUSTOMER C
WHERE NOT EXISTS (
	SELECT 1
	FROM ORDERS O
	WHERE C.CUSTOMER_ID = O.CUSTOMER_ID AND STATUS = 'DELIVERED'
);

-- Câu 3
-- Tìm khách hàng GOLD có loyalty_points lớn hơn tất cả khác PLATINUM
SELECT 
	CUSTOMER_ID,
	CUSTOMER_NAME,
	LOYALTY_POINTS
FROM CUSTOMER C
WHERE VIP_TIER = 'GOLD' AND LOYALTY_POINTS > ALL (
	SELECT 
		LOYALTY_POINTS
	FROM CUSTOMER 
	WHERE VIP_TIER = 'PLATINUM'
)

-- Câu 4
-- Tìm khách hàng SILVER có loyalty_points >= ít nhất một khách GOLD
SELECT 
	CUSTOMER_ID,
	CUSTOMER_NAME,
	LOYALTY_POINTS
FROM CUSTOMER C
WHERE VIP_TIER = 'SILVER' AND LOYALTY_POINTS >= ANY (
	SELECT 
		LOYALTY_POINTS
	FROM CUSTOMER 
	WHERE VIP_TIER = 'GOLD'
)

