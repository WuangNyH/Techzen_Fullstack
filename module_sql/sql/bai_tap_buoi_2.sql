	STATUS
FROM
	ORDERS
WHERE
	STATUS = 'DELIVERED'
LIMIT
	20
OFFSET
	20 * (3 - 1);

-- Câu 2
SELECT
	CONCAT(CUSTOMER_NAME, ' ', EMAIL, ' ', PHONE) AS FULL_INFO,
	LENGTH(CUSTOMER_NAME) AS NAME_LENGTH,
	SUBSTRING(EMAIL, POSITION('@' IN EMAIL) + 1),
	CREATED_AT
FROM
	CUSTOMER
ORDER BY
	CREATED_AT DESC
LIMIT
	10;

-- Câu 3
SELECT
	ID,
	ORDER_NUMBER,
	TOTAL_AMOUNT,
	CASE
		WHEN TOTAL_AMOUNT < 50 THEN 'Rất nhỏ'
		WHEN TOTAL_AMOUNT BETWEEN 50 AND 199  THEN 'Nhỏ'
		WHEN TOTAL_AMOUNT BETWEEN 200 AND 999  THEN 'Trung bình'
		ELSE 'Lớn'
	END AS ORDER_VALUE_LEVEL,
	CREATED_AT
FROM
	ORDERS
ORDER BY
	CREATED_AT DESC
LIMIT
	100;