-- Câu 1
SELECT
	UPPER(CUSTOMER_NAME) AS TEN_KHACH_HANG,
	LOWER(EMAIL) AS EMAIL
FROM
	CUSTOMER
LIMIT
	10;

-- Câu 2
SELECT
	ID,
	ORDER_NUMBER,
	TOTAL_AMOUNT * 1.1 AS TONG_SAU_THUE
FROM
	ORDERS
WHERE
	TOTAL_AMOUNT BETWEEN 100 AND 500;

-- Câu 3
SELECT
	CUSTOMER_ID,
	CUSTOMER_NAME,
	VIP_TIER
FROM
	CUSTOMER
WHERE
	VIP_TIER IN ('GOLD', 'PLATINUM')
ORDER BY
	CUSTOMER_NAME
LIMIT
	1000
OFFSET
	500;

-- Câu 4
SELECT DISTINCT
	CITY
FROM
	CUSTOMER
WHERE
	VIP_TIER IN ('GOLD', 'PLATINUM')
	AND IS_ACTIVE = TRUE
ORDER BY
	CITY;

-- Câu 5
SELECT
	ID,
	ORDER_NUMBER,
	STATUS,
	CASE
		WHEN STATUS = 'PENDING' THEN 'Chờ xử lý'
		WHEN STATUS IN ('PAID', 'SHIPPED') THEN 'Đang thực hiện'
		ELSE 'Khác'
	END AS TRANG_THAI_DON_HANG
FROM
	ORDERS;

-- Câu 6
SELECT
	CUSTOMER_ID,
	CUSTOMER_NAME,
	CASE
		WHEN CUSTOMER_NAME LIKE 'Je%' THEN 'Tên bắt đầu bằng Je'
		WHEN CUSTOMER_NAME ILIKE '%smith%' THEN 'Tên có chứa Smith'
		ELSE 'Khác'
	END AS PHAN_LOAI_THEO_TEN
FROM
	CUSTOMER
LIMIT 100;

